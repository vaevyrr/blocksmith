#!/usr/bin/env python3
"""Generate a basic paired Minecraft Bedrock behavior/resource pack scaffold."""
import argparse
import json
import re
import uuid
from pathlib import Path


def safe_name(value):
    value = value.lower().replace("-", "_").replace(" ", "_")
    if not re.fullmatch(r"[a-z0-9_]{1,40}", value):
        raise ValueError("project name may contain lowercase letters, numbers and underscores")
    return value


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def generate(name, output, force=False):
    name = safe_name(name)
    bp = output / f"{name}_BP"
    rp = output / f"{name}_RP"
    if (bp.exists() or rp.exists()) and not force:
        raise FileExistsError("pack directory already exists; pass --force to replace generated files")
    bp.mkdir(parents=True, exist_ok=True)
    rp.mkdir(parents=True, exist_ok=True)
    bp_header, bp_module = str(uuid.uuid4()), str(uuid.uuid4())
    rp_header, rp_module = str(uuid.uuid4()), str(uuid.uuid4())
    write_json(bp / "manifest.json", {
        "format_version": 2,
        "header": {"name": f"{name} Behavior", "description": "Generated by BlockSmith",
                   "uuid": bp_header, "version": [1, 0, 0], "min_engine_version": [1, 20, 0]},
        "modules": [{"type": "data", "uuid": bp_module, "version": [1, 0, 0]}],
        "dependencies": [{"uuid": rp_header, "version": [1, 0, 0]}]
    })
    write_json(rp / "manifest.json", {
        "format_version": 2,
        "header": {"name": f"{name} Resources", "description": "Generated by BlockSmith",
                   "uuid": rp_header, "version": [1, 0, 0], "min_engine_version": [1, 20, 0]},
        "modules": [{"type": "resources", "uuid": rp_module, "version": [1, 0, 0]}]
    })
    write_json(bp / "items" / "sample_item.json", {
        "format_version": "1.20.0",
        "minecraft:item": {"description": {"identifier": f"{name}:sample_item"},
                           "components": {"minecraft:max_stack_size": 64}}
    })
    write_json(bp / "blocks" / "sample_block.json", {
        "format_version": "1.20.0",
        "minecraft:block": {"description": {"identifier": f"{name}:sample_block"},
                            "components": {"minecraft:destructible_by_mining": {"seconds_to_destroy": 1.5},
                                           "minecraft:map_color": "#8A8A8A"}}
    })
    write_json(rp / "textures" / "item_texture.json", {
        "resource_pack_name": name, "texture_name": "atlas.items",
        "texture_data": {"sample_item": {"textures": "textures/items/sample_item"}}
    })
    write_json(rp / "textures" / "terrain_texture.json", {
        "resource_pack_name": name, "texture_name": "atlas.terrain",
        "texture_data": {"sample_block": {"textures": "textures/blocks/sample_block"}}
    })
    (output / "README.txt").write_text(
        f"Generated project: {name}\nBehavior pack: {bp}\nResource pack: {rp}\n"
        "Add matching PNG textures under the referenced texture paths before importing.\n",
        encoding="utf-8")
    return bp, rp


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    create = sub.add_parser("create", help="create a paired behavior/resource pack")
    create.add_argument("name")
    create.add_argument("--output", type=Path, default=Path("."))
    create.add_argument("--force", action="store_true")
    args = parser.parse_args()
    try:
        bp, rp = generate(args.name, args.output, args.force)
        print(f"Created {bp} and {rp}")
    except (OSError, ValueError) as exc:
        parser.exit(2, f"blocksmith: {exc}\n")


if __name__ == "__main__":
    main()
