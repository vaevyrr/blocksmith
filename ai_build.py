from __future__ import annotations
import json
import re
import uuid
from pathlib import Path
from typing import Any
from ai_schema import PackSpec

def _id(value: Any, fallback: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_]+", "_", str(value or "").strip().lower()).strip("_")
    return value or fallback

def _write(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

def _uuid() -> str:
    return str(uuid.uuid4())

def build_bedrock(spec: PackSpec, output: Path, force: bool = False) -> Path:
    name = _id(spec.name, "pack"); root = output / name; bp = root / f"{name}_BP"; rp = root / f"{name}_RP"
    if root.exists() and not force: raise FileExistsError(f"{root} already exists. Enable replace to overwrite it.")
    bp.mkdir(parents=True, exist_ok=True); rp.mkdir(parents=True, exist_ok=True)
    bh,bm,rh,rm=_uuid(),_uuid(),_uuid(),_uuid()
    _write(bp/"manifest.json",{"format_version":2,"header":{"name":f"{spec.name} Behavior","description":spec.description or "Generated by BlockSmith AI","uuid":bh,"version":[1,0,0],"min_engine_version":[1,21,0]},"modules":[{"type":"data","uuid":bm,"version":[1,0,0]}],"dependencies":[{"uuid":rh,"version":[1,0,0]}]})
    _write(rp/"manifest.json",{"format_version":2,"header":{"name":f"{spec.name} Resources","description":spec.description or "Generated by BlockSmith AI","uuid":rh,"version":[1,0,0],"min_engine_version":[1,21,0]},"modules":[{"type":"resources","uuid":rm,"version":[1,0,0]}]})
    for item in spec.items:
        iid=_id(item.get("id"),"item"); components={"minecraft:max_stack_size":max(1,min(64,int(item.get("max_stack_size",1))))}
        if item.get("damage") is not None: components["minecraft:damage"]=int(item["damage"])
        if item.get("durability") is not None: components["minecraft:durability"]={"max_durability":int(item["durability"])}
        _write(bp/"items"/f"{iid}.json",{"format_version":"1.21.0","minecraft:item":{"description":{"identifier":f"{spec.namespace}:{iid}","menu_category":{"category":"items"}},"components":components}})
    for block in spec.blocks:
        bid=_id(block.get("id"),"block")
        _write(bp/"blocks"/f"{bid}.json",{"format_version":"1.21.0","minecraft:block":{"description":{"identifier":f"{spec.namespace}:{bid}","menu_category":{"category":"construction"}},"components":{"minecraft:destructible_by_mining":{"seconds_to_destroy":float(block.get("hardness",1.0))}}}})
    for recipe in spec.recipes:
        rid=_id(recipe.get("id"),"recipe")
        if recipe.get("type","shaped")=="shaped":
            _write(bp/"recipes"/f"{rid}.json",{"format_version":"1.20.10","minecraft:recipe_shaped":{"description":{"identifier":f"{spec.namespace}:{rid}"},"tags":["crafting_table"],"pattern":recipe.get("pattern",["A"]),"key":recipe.get("key",{"A":"minecraft:stone"}),"result":{"item":str(recipe.get("result",f"{spec.namespace}:item")),"count":int(recipe.get("count",1))}}})
    for function in spec.functions:
        fn=_id(function.get("name"),"function"); commands=function.get("commands",[])
        if isinstance(commands,list):
            path=bp/"functions"/f"{fn}.mcfunction"; path.parent.mkdir(parents=True,exist_ok=True); path.write_text("\n".join(str(x) for x in commands)+"\n",encoding="utf-8")
    (root/"blocksmith-plan.json").write_text(json.dumps(spec.__dict__,indent=2)+"\n",encoding="utf-8")
    (root/"README.txt").write_text(f"{spec.name}\nPlatform: Bedrock\nGenerated by BlockSmith AI with local Ollama.\n\nReview generated content against your Minecraft version before importing.\n",encoding="utf-8")
    return root

def build_java(spec: PackSpec, output: Path, force: bool = False) -> Path:
    name=_id(spec.name,"pack"); root=output/name; datapack=root/"datapack"; resourcepack=root/"resourcepack"
    if root.exists() and not force: raise FileExistsError(f"{root} already exists. Enable replace to overwrite it.")
    datapack.mkdir(parents=True,exist_ok=True); resourcepack.mkdir(parents=True,exist_ok=True)
    _write(datapack/"pack.mcmeta",{"pack":{"pack_format":48,"description":spec.description or f"{spec.name} - BlockSmith AI"}})
    _write(resourcepack/"pack.mcmeta",{"pack":{"pack_format":34,"description":spec.description or f"{spec.name} resources"}})
    ns=spec.namespace
    for function in spec.functions:
        fn=_id(function.get("name"),"function"); path=datapack/"data"/ns/"function"/f"{fn}.mcfunction"; path.parent.mkdir(parents=True,exist_ok=True); path.write_text("\n".join(str(x) for x in function.get("commands",[]))+"\n",encoding="utf-8")
    for recipe in spec.recipes:
        rid=_id(recipe.get("id"),"recipe"); data={"type":"minecraft:crafting_shaped","pattern":recipe.get("pattern",["A"]),"key":{k:{"item":v} for k,v in recipe.get("key",{"A":"minecraft:stone"}).items()},"result":{"id":str(recipe.get("result",f"{ns}:{rid}")),"count":int(recipe.get("count",1))}}
        _write(datapack/"data"/ns/"recipe"/f"{rid}.json",data)
    (root/"blocksmith-plan.json").write_text(json.dumps(spec.__dict__,indent=2)+"\n",encoding="utf-8")
    (root/"README.txt").write_text(f"{spec.name}\nPlatform: Java\nGenerated by BlockSmith AI with local Ollama.\n\nJava mode currently targets datapack/resource-pack scaffolding. Fabric/NeoForge generation is not enabled yet.\n",encoding="utf-8")
    return root

def build(spec: PackSpec, output: Path, force: bool = False) -> Path:
    output.mkdir(parents=True,exist_ok=True)
    return build_java(spec,output,force) if spec.platform=="java" else build_bedrock(spec,output,force)
